-- Clarksons tanker report ingestion: tables + analytic views
-- Adjust database/schema names to your conventions.
CREATE SCHEMA IF NOT EXISTS RESEARCH.FREIGHT;
USE SCHEMA RESEARCH.FREIGHT;

-- One row per email. Keeps the full body so any day can be re-parsed after a parser fix.
CREATE TABLE IF NOT EXISTS RAW_EMAILS (
  REPORT_ID STRING, REPORT_TYPE STRING, REPORT_DATE DATE, RECEIVED_AT TIMESTAMP_TZ,
  SUBJECT STRING, SENDER STRING, INTERNET_MESSAGE_ID STRING, BODY_SHA256 STRING,
  BODY_TEXT STRING, ATTACHMENT_NAMES STRING, HEADLINE STRING, TURKISH_STRAITS STRING,
  BALTIC_DATE DATE, PARSER_VERSION STRING, N_FIXTURES INT, N_CARGOES INT, N_UNPARSED INT,
  LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS FIXTURES (
  SECTION STRING, BLOCK STRING, LINE_NO INT, FORMAT STRING, VESSEL STRING, BUILT_YY STRING,
  QTY_KT FLOAT, CARGO_GRADE STRING, LOAD STRING, DISCHARGE STRING, LAYCAN_RAW STRING,
  LAYCAN_START DATE, LAYCAN_END DATE, RATE_RAW STRING, RATE_TYPE STRING, WS_LOW FLOAT,
  WS_HIGH FLOAT, LUMPSUM_USD FLOAT, RATE_QUALIFIER STRING, CHARTERER STRING, STATUS STRING,
  REPORTED BOOLEAN, RELET_BY STRING, OR_OTHER_VESSEL STRING, STATUS_RAW STRING,
  OPEN_PORT STRING, OPEN_DATE DATE, RAW_LINE STRING,
  REPORT_TYPE STRING, REPORT_DATE DATE, REPORT_ID STRING, PARSER_VERSION STRING
);

CREATE TABLE IF NOT EXISTS CARGOES (
  SECTION STRING, LINE_NO INT, CHARTERER STRING, QTY_KT FLOAT, LOAD STRING, DISCHARGE STRING,
  LAYCAN_RAW STRING, LAYCAN_START DATE, LAYCAN_END DATE, NOTES STRING, REPORTED BOOLEAN,
  REPLACES_VESSEL STRING, RAW_LINE STRING,
  REPORT_TYPE STRING, REPORT_DATE DATE, REPORT_ID STRING, PARSER_VERSION STRING
);

CREATE TABLE IF NOT EXISTS BALTIC_ASSESSMENTS (
  ROUTE STRING, ASSESSMENT_DATE DATE, QTY_KT FLOAT, VALUE FLOAT, UNIT STRING, CHANGE FLOAT,
  TCE_USD_DAY FLOAT, RAW_LINE STRING,
  REPORT_TYPE STRING, REPORT_DATE DATE, REPORT_ID STRING, PARSER_VERSION STRING
);

CREATE TABLE IF NOT EXISTS BUNKER_PRICES (
  PORT STRING, GRADE STRING, PRICE_USD_MT FLOAT, CHANGE FLOAT, RAW_LINE STRING,
  REPORT_TYPE STRING, REPORT_DATE DATE, REPORT_ID STRING, PARSER_VERSION STRING
);

CREATE TABLE IF NOT EXISTS MARKET_PRICES (
  INSTRUMENT STRING, VALUE FLOAT, CHANGE FLOAT, UNIT STRING, RAW_LINE STRING,
  REPORT_TYPE STRING, REPORT_DATE DATE, REPORT_ID STRING, PARSER_VERSION STRING
);

CREATE TABLE IF NOT EXISTS DECADE_COUNTS (
  METRIC STRING, MONTH DATE, DECADE STRING, VALUE FLOAT, RAW_LINE STRING,
  REPORT_TYPE STRING, REPORT_DATE DATE, REPORT_ID STRING, PARSER_VERSION STRING
);

-- Lines the regex parser could not handle. Review these; they are the signal that
-- Clarksons changed a format.
CREATE TABLE IF NOT EXISTS PARSE_EXCEPTIONS (
  SECTION STRING, BLOCK STRING, LINE_NO INT, RAW_LINE STRING,
  REPORT_TYPE STRING, REPORT_DATE DATE, REPORT_ID STRING, PARSER_VERSION STRING
);

-- ---------------------------------------------------------------------- views

-- Baltic prints, one row per route per assessment date (both reports carry some routes).
CREATE OR REPLACE VIEW V_BALTIC_DAILY AS
SELECT ROUTE, ASSESSMENT_DATE, VALUE, UNIT, CHANGE, TCE_USD_DAY
FROM BALTIC_ASSESSMENTS
QUALIFY ROW_NUMBER() OVER (PARTITION BY ROUTE, ASSESSMENT_DATE ORDER BY REPORT_DATE DESC) = 1;

-- Life of each fixture across daily reports: first seen, latest status, days on subs.
-- Vessel + laycan start identifies a deal; position-format lines (no laycan) use open date.
CREATE OR REPLACE VIEW V_FIXTURE_LIFECYCLE AS
WITH f AS (
  SELECT *, VESSEL || '|' || COALESCE(TO_VARCHAR(LAYCAN_START), 'OPEN ' || TO_VARCHAR(OPEN_DATE)) AS DEAL_KEY
  FROM FIXTURES WHERE VESSEL NOT IN ('TBN')
)
SELECT DEAL_KEY, REPORT_TYPE, ANY_VALUE(VESSEL) AS VESSEL, ANY_VALUE(SECTION) AS SECTION,
       MAX(LOAD) AS LOAD, MAX(DISCHARGE) AS DISCHARGE, MAX(CHARTERER) AS CHARTERER,
       MAX(WS_LOW) AS WS_LOW, MAX(WS_HIGH) AS WS_HIGH, MAX(LUMPSUM_USD) AS LUMPSUM_USD,
       MIN(REPORT_DATE) AS FIRST_SEEN, MAX(REPORT_DATE) AS LAST_SEEN,
       MAX_BY(STATUS, REPORT_DATE) AS LATEST_STATUS,
       DATEDIFF('day', MIN(IFF(STATUS = 'ON_SUBS', REPORT_DATE, NULL)),
                MIN(IFF(STATUS IN ('FULLY_FIXED', 'FAILED'), REPORT_DATE, NULL))) AS DAYS_ON_SUBS,
       MAX(RELET_BY) AS RELET_BY
FROM f GROUP BY DEAL_KEY, REPORT_TYPE;

-- Weekly fail rate by report: share of resolved deals that failed.
CREATE OR REPLACE VIEW V_FAIL_RATE_WEEKLY AS
SELECT REPORT_TYPE, DATE_TRUNC('week', LAST_SEEN) AS WEEK,
       COUNT_IF(LATEST_STATUS = 'FAILED') AS FAILED,
       COUNT_IF(LATEST_STATUS IN ('FAILED', 'FULLY_FIXED', 'ON_SUBS')) AS DEALS,
       FAILED / NULLIF(DEALS, 0) AS FAIL_RATE
FROM V_FIXTURE_LIFECYCLE GROUP BY 1, 2;

-- MEG ships (ex subs) per cargo, by decade, using the latest report for each decade.
CREATE OR REPLACE VIEW V_MEG_SHIPS_PER_CARGO AS
WITH latest AS (
  SELECT METRIC, MONTH, DECADE, VALUE, REPORT_DATE
  FROM DECADE_COUNTS WHERE VALUE IS NOT NULL
  QUALIFY ROW_NUMBER() OVER (PARTITION BY METRIC, MONTH, DECADE ORDER BY REPORT_DATE DESC) = 1
)
SELECT s.MONTH, s.DECADE, s.VALUE AS SHIPS_EX_SUBS, c.VALUE AS CARGOES,
       s.VALUE / NULLIF(c.VALUE, 0) AS SHIPS_PER_CARGO, s.REPORT_DATE AS SHIPS_AS_OF
FROM latest s
LEFT JOIN latest c ON c.METRIC = 'MEG_CARGOES' AND c.MONTH = s.MONTH AND c.DECADE = s.DECADE
WHERE s.METRIC = 'MEG_SHIPS_EX_SUBS';

-- Fujairah VLSFO premium over Singapore and Rotterdam: a stress gauge for Gulf bunkering.
CREATE OR REPLACE VIEW V_BUNKER_SPREADS AS
SELECT REPORT_DATE,
       MAX(IFF(PORT = 'FUJAIRAH', PRICE_USD_MT, NULL)) - MAX(IFF(PORT = 'SINGAPORE', PRICE_USD_MT, NULL)) AS FUJ_MINUS_SING,
       MAX(IFF(PORT = 'FUJAIRAH', PRICE_USD_MT, NULL)) - MAX(IFF(PORT = 'ROTTERDAM', PRICE_USD_MT, NULL)) AS FUJ_MINUS_RDAM
FROM BUNKER_PRICES
WHERE GRADE IN ('VLSFO', '0.5% MARINE FUEL') AND REPORT_TYPE = 'VLCC_EVENING'
GROUP BY REPORT_DATE;
